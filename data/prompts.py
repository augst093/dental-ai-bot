def load_knowledge_base_text() -> str:
    """Загружает базу знаний клиники из JSON файла и форматирует её в читаемый текст для LLM."""
    kb_path = Path(__file__).resolve().parent / "knowledge_base.json"
    try:
        with open(kb_path, "r", encoding="utf-8") as f:
            data = json.load(f)
        return json.dumps(data, ensure_ascii=False, indent=2)
    except Exception as e:
        return f"Error loading knowledge base: {e}"


